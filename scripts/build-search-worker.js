const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const outputPath = path.join(root, 'src', 'search-worker-source.js');

function buildSearchWorkerSource() {
  const worker = fs.readFileSync(path.join(root, 'src', 'search-worker.js'), 'utf8')
    .replace(/\r\n/g, '\n');
  const imports = /^importScripts\([\s\S]*?\);/m.exec(worker);
  if (!imports) throw new Error('Search worker import list is missing.');
  let files;
  vm.runInNewContext(imports[0], {
    importScripts(...values) { files = values; },
  }, { timeout: 1000 });
  const cores = files.map(file => {
    const filename = file.split('?')[0];
    if (!/^\.\/[-a-z0-9]+\.js$/.test(filename)) {
      throw new Error(`Unexpected search worker dependency: ${file}`);
    }
    return fs.readFileSync(path.join(root, 'src', filename), 'utf8')
      .replace(/\r\n/g, '\n');
  });
  return [...cores, worker.slice(0, imports.index)
    + worker.slice(imports.index + imports[0].length)].join('\n;\n');
}

function buildSearchWorkerBundle() {
  return '// Generated by node scripts/build-search-worker.js. Do not edit.\n'
    + `globalThis.StormDokuSearchWorkerSource = ${JSON.stringify(buildSearchWorkerSource())};\n`;
}

if (require.main === module) {
  const bundle = buildSearchWorkerBundle();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(outputPath)
      || fs.readFileSync(outputPath, 'utf8').replace(/\r\n/g, '\n') !== bundle) {
      console.error('Offline search worker is stale. Run node scripts/build-search-worker.js.');
      process.exitCode = 1;
    }
  } else {
    fs.writeFileSync(outputPath, bundle);
    console.log('Updated src/search-worker-source.js');
  }
}

module.exports = { buildSearchWorkerSource, buildSearchWorkerBundle };
